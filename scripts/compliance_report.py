"""Write the Arizona hospital price transparency compliance report as Markdown.

Usage:
    uv run python scripts/compliance_report.py

Reads raw.compliance_checks, marts.hospital_compliance_scores and the discovery and parse
results, and writes docs/reports/arizona-compliance-<yyyy-mm-dd>.md. Run it after the
warehouse build (Dagster's build_warehouse job) so the numbers match the checks.
"""

import os
from pathlib import Path

import polars as pl
import psycopg

DATABASE_URL = os.environ.get("DATABASE_URL", "postgresql://pt:pt@localhost:5432/prices")
OUT_DIR = Path("docs/reports")
RULE_NAMES = {
    "cms_hpt_lists_hospital": "cms-hpt.txt names the hospital's price file",
    "cms_hpt_machine_readable": "cms-hpt.txt is well-formed and readable by a program",
    "price_file_downloads": "Price file downloads",
    "price_file_parses": "Price file reads as a CMS template file",
    "version_stated": "Template version stated",
    "header_fields_present": "Required header fields filled in",
    "payer_prices_present": "Payer-specific negotiated charges present",
    "mostly_dollar_prices": "At least half of unbundled insurer prices in dollars",
    "updated_within_12_months": "Updated in the last 12 months",
}


def query(conn: psycopg.Connection, sql: str) -> pl.DataFrame:
    cur = conn.execute(sql)
    return pl.DataFrame(cur.fetchall(), schema=[d.name for d in cur.description], orient="row")


def table(df: pl.DataFrame) -> str:
    head = "| " + " | ".join(df.columns) + " |"
    rule = "| " + " | ".join("---" for _ in df.columns) + " |"
    rows = ["| " + " | ".join("" if v is None else str(v) for v in r) + " |" for r in df.rows()]
    return "\n".join([head, rule, *rows])


def main() -> None:
    with psycopg.connect(DATABASE_URL) as conn:
        checks = query(
            conn, "SELECT ccn, rule, passed, detail, checked_at FROM raw.compliance_checks"
        )
        scores = query(
            conn,
            """
            SELECT ccn, initcap(name) AS hospital, initcap(city) AS city, hospital_type,
                   rules_checked, rules_passed, score_pct, failed_rules
            FROM marts.hospital_compliance_scores ORDER BY score_pct NULLS LAST, name""",
        )
    checked_on = checks["checked_at"].max().date()
    pretty_date = f"{checked_on:%B} {checked_on.day}, {checked_on:%Y}"  # %-d isn't portable
    n = scores.height

    def passing(rule: str) -> set[str]:
        return set(checks.filter((pl.col("rule") == rule) & pl.col("passed"))["ccn"])

    usable = passing("payer_prices_present") & passing("mostly_dollar_prices")
    findable = passing("cms_hpt_lists_hospital")
    readable = passing("cms_hpt_machine_readable")
    perfect = scores.filter(pl.col("score_pct") == 100).height

    by_rule = (
        checks.group_by("rule")
        .agg(pl.col("passed").sum().alias("Pass"), (~pl.col("passed")).sum().alias("Fail"),
             pl.col("passed").is_null().sum().alias("Not checked"))
        .with_columns(pl.col("rule").replace_strict(RULE_NAMES).alias("Rule"),
                      pl.col("rule").replace_strict({r: i for i, r in enumerate(RULE_NAMES)})
                      .alias("order"))
        .sort("order").select("Rule", "Pass", "Fail", "Not checked")
    )  # fmt: skip
    statuses = (
        checks.filter(pl.col("rule") == "cms_hpt_lists_hospital")
        .group_by(pl.col("detail").alias("cms-hpt.txt status"))
        .agg(pl.len().alias("Hospitals"))
        .sort("Hospitals", descending=True)
    )
    hospitals = scores.select(
        pl.col("hospital").alias("Hospital"), pl.col("city").alias("City"),
        pl.col("hospital_type").alias("Type"),
        pl.format("{}%", pl.col("score_pct")).alias("Score"),
        pl.format("{}/{}", pl.col("rules_passed"), pl.col("rules_checked")).alias("Passed"),
        pl.col("failed_rules").fill_null("").str.replace_all("_", " ").alias("Failed rules"),
    )  # fmt: skip

    report = f"""# Arizona hospital price transparency: compliance check

Checked {pretty_date} · {n} hospitals in scope (federally run VA, Indian Health
Service and tribal hospitals excluded) · generated by `scripts/compliance_report.py`

## Summary

- **{perfect} of {n} hospitals ({perfect / n:.0%}) pass every rule we can check.**
- **{len(findable)} of {n} ({len(findable) / n:.0%})** have a `cms-hpt.txt` file at their
  website root that names their price file, as CMS requires; only **{len(readable)}**
  ({len(readable) / n:.0%}) serve it in a form a program can read without help.
- **{len(usable)} of {n} ({len(usable) / n:.0%}) publish usable insurer prices**: their file
  has payer-specific negotiated charges, mostly as dollar amounts rather than percentages
  or formulas.

## Results by rule

{table(by_rule)}

"Not checked" means the hospital's file couldn't be obtained or read, so its contents
weren't tested; those hospitals already fail the earlier rules.

## How each hospital's file was found

{table(statuses)}

- `found_browser_ua_only`: served only to clients claiming to be a web browser.
- `found_manual_copy`: blocked for programs by a bot challenge; copied by hand in a browser.
- `found_malformed`: the price file can be found, but `cms-hpt.txt` isn't in CMS's format.
- `blocked_bot_challenge`: a bot challenge blocks programs; not yet copied by hand.
- `no_matching_location`: the file doesn't list this hospital (one names a different
  hospital entirely).

## Every hospital

{table(hospitals)}

## Method and caveats

- **What is tested.** Nine rules we can check from outside the hospital, based on our
  reading of 45 CFR 180.50 and CMS's data dictionary. This is not CMS's own determination.
- **Spot-checked against CMS.** CMS's validator (`@cmsgov/hpt-validator-cli` 1.10.8) agreed
  on the five files compared. It checks format, not substance: it passes a file with no
  insurer prices, which our "payer-specific negotiated charges present" rule fails.
- **Dates.** CMS requires ISO 8601 dates but also accepts M/D/YYYY and MM/DD/YYYY in CSV
  files, so those are not counted as failures.
- **Bundled prices.** Prices marked as bundled into a DRG case rate are not counted against
  the dollar-amount rule.
- **Too large to read yet.** Mayo Clinic Arizona's price file is 21.5 GB; its contents are
  not yet checked.
- **Snapshot.** Hospitals update their files; this reflects {pretty_date}.
"""
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    out = OUT_DIR / f"arizona-compliance-{checked_on:%Y-%m-%d}.md"
    out.write_text(report, encoding="utf-8", newline="\n")
    print(f"{out}: {n} hospitals, {perfect} perfect, {len(usable)} with usable insurer prices")


if __name__ == "__main__":
    main()
